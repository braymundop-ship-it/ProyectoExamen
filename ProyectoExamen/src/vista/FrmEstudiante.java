    private void cmbCarreraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbCarreraActionPerformed
    String carrera = cmbCarrera.getSelectedItem().toString();

if (carrera.equals("Ingeniería")) {
    txtCuotaMensual.setText("930");
} else if (carrera.equals("Arquitectura")) {
    txtCuotaMensual.setText("1200");
} else if (carrera.equals("Medicina")) {
    txtCuotaMensual.setText("750");
}
    }//GEN-LAST:event_cmbCarreraActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
    try {
    Estudiante est = new Estudiante();

    est.setCarnet(txtCarnet.getText());
    est.setFirstName(txtFirstName.getText());
    est.setSecondName(txtSecondName.getText());
    est.setLastName(txtLastName.getText());
    est.setDireccion(txtDireccion.getText());

    est.setTelefono(Integer.parseInt(txtTelefono.getText()));

    est.setCarrera(cmbCarrera.getSelectedItem().toString());

    est.setFechaNacimiento(Date.valueOf(txtFechaNacimiento.getText()));
    est.setFechaIngreso(Date.valueOf(txtFechaIngreso.getText()));

    est.setCuotaMensual(Double.parseDouble(txtCuotaMensual.getText()));

    EstudianteController controller = new EstudianteController();

    if (controller.guardarEstudiante(est)) {
        JOptionPane.showMessageDialog(this, "Estudiante guardado correctamente");
    } else {
        JOptionPane.showMessageDialog(this, "Error al guardar estudiante");
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    try {
    String carnet = txtCarnet.getText();

    EstudianteController controller = new EstudianteController();
    Estudiante est = controller.consultarEstudiante(carnet);

    if (est != null) {

        txtFirstName.setText(est.getFirstName());
        txtSecondName.setText(est.getSecondName());
        txtLastName.setText(est.getLastName());
        txtDireccion.setText(est.getDireccion());
        txtTelefono.setText(String.valueOf(est.getTelefono()));

        cmbCarrera.setSelectedItem(est.getCarrera());

        txtFechaNacimiento.setText(est.getFechaNacimiento().toString());
        txtFechaIngreso.setText(est.getFechaIngreso().toString());

        txtCuotaMensual.setText(String.valueOf(est.getCuotaMensual()));

    } else {
        JOptionPane.showMessageDialog(this, "Estudiante no encontrado");
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}
    }//GEN-LAST:event_jButton2ActionPerformed

